  const run=async text=>{await input.fill(text);await input.press('Enter')}
  assert.equal(await input.evaluate(el=>document.activeElement===el),true)
  assert.equal(await dialog.locator('.term-wordmark span').evaluate(el=>getComputedStyle(el).animationName),'none')
  await page.emulateMedia({reducedMotion:'no-preference'})
  assert.equal(await dialog.locator('.term-wordmark span').evaluate(el=>getComputedStyle(el).animationName),'term-blink')
  assert.deepEqual(await dialog.locator('.term-wordmark span').evaluate(el=>{const animation=el.getAnimations()[0];animation.pause();animation.currentTime=100;const on=getComputedStyle(el).opacity;animation.currentTime=650;const off=getComputedStyle(el).opacity;return [on,off]}),['1','0'])
