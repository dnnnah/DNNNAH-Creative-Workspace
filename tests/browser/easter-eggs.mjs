 await terminal()
 await command('help')
 const help = await page.locator('.term-output').last().innerText()
 assert.match(help, /easter/); assert.doesNotMatch(help, /sudo|git blame/)
 await command('easter'); assert.match(await page.locator('.term-output').last().innerText(), /git log --oneline/)
 await command('sudo rm -rf /')
 await page.waitForTimeout(550)
 assert.equal(await page.locator('#term-input').getAttribute('readonly'), '')
 await page.keyboard.press('Control+c')
 await page.getByText('Simulación cancelada. Todo sigue aquí.').waitFor()
 await page.waitForFunction(() => !document.getElementById('term-input').readOnly)
 await command('sudo rm -rf /')
 await page.getByText('¡Es broma! 😅 No se ha eliminado nada.').waitFor()
 assert.match(await page.locator('.term-demolition').last().innerText(), /100%/)
 const jokeBox = await page.getByText('¡Es broma! 😅 No se ha eliminado nada.').boundingBox()
 const scrollBox = await page.locator('.term-scroll').boundingBox()
 assert.ok(jokeBox.y >= scrollBox.y && jokeBox.y + jokeBox.height <= scrollBox.y + scrollBox.height, 'El remate debe quedar visible al terminar')
 await page.screenshot({ path: `${captures}/rm-desktop.png` })
