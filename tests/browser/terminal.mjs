import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH })
const directory = process.env.TERMINAL_CAPTURES || 'outputs/terminal'
await mkdir(directory, { recursive: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const base = process.env.PORTFOLIO_URL || 'http://127.0.0.1:5179'
const dialog = page.getByRole('dialog', { name: 'Terminal', exact: true })
const input = dialog.getByRole('textbox')
async function open(en = false) {
  await page.getByRole('button', { name: en ? 'Open menu' : 'Abrir menú', exact: true }).click()
  await page.getByRole('button', { name: 'Terminal', exact: true }).click()
  await dialog.waitFor({ state: 'visible' })
  assert.equal(await page.locator('dialog[open]').count(), 1)
}
async function run(command) { await input.fill(command); await input.press('Enter') }
try {
  await page.goto(base)
  await open()
  assert.equal(await input.evaluate(el => el === document.activeElement), true)
  assert.equal(await page.locator('body').evaluate(el => el.style.overflow), 'hidden')
  if (!process.env.SKIP_CAPTURES) await page.screenshot({ path: `${directory}/terminal-desktop.png` })
  for (const [command, expected] of [['help', 'sudo rm -rf /'], ['ls', 'hero.tsx'], ['cat hero.tsx', 'Donnovan'], ['cat about.md', 'UDG / CUCEI'], ['cat skills.ts', 'Playwright'], ['cat projects/', 'Protech'], ['cat contact.tsx', 'Abrir Contact'], ['skills', 'TypeScript'], ['stack', 'TypeScript'], ['projects', 'PawPass'], ['whoami', 'Donnovan'], ['git blame', '00000000 (Donnovan 1)'], ['curl cheat-sheet', 'Shift+Tab'], ['sudo make-coffee', 'imaginario'], ['sudo rm -rf /', 'no se ha eliminado nada'], ['nonsense', 'Comando desconocido'], ['cat ../../.env', 'Archivo desconocido']]) {
    await run(command)
    assert.ok((await dialog.getByRole('log').innerText()).includes(expected), command)
  }
  assert.equal(await dialog.getByRole('link', { name: 'PawPass', exact: true }).last().getAttribute('href'), '#projects/pawpass')
  const requests = []
  const recordRequest = request => requests.push(request.url())
  page.on('request', recordRequest)
  const originalUrl = page.url()
  for (const command of ['sudo rm -rf /', 'sudo rm -rf /; whoami', 'open https://evil.test', '<script>window.hacked=true</script>']) await run(command)
  assert.equal(page.url(), originalUrl)
  assert.equal(await page.evaluate(() => window.hacked), undefined)
  assert.equal(await dialog.locator('script').count(), 0)
  assert.deepEqual(requests, [], 'Los comandos de simulación no generan peticiones')
  page.off('request', recordRequest)
  await run('cat ../../.env')
  await input.fill('borrador')
  await input.press('ArrowUp')
  assert.equal(await input.inputValue(), 'cat ../../.env')
  await input.press('ArrowDown')
  assert.equal(await input.inputValue(), 'borrador')
  await input.fill('sudo m')
  await input.press('Tab')
  assert.equal(await input.inputValue(), 'sudo make-coffee')
  await input.fill('s')
  await input.press('Tab')
  assert.match(await dialog.getByRole('status').innerText(), /skills.*stack/s)
  await input.press('Shift+Tab')
  assert.equal(await dialog.evaluate(el => el.contains(document.activeElement)), true)
  await input.focus()
  await run('matrix')
  assert.equal(await dialog.locator('.term-matrix').count(), 1)
  assert.equal(await dialog.locator('.term-matrix').evaluate(el => getComputedStyle(el.firstElementChild).animationName), 'none')
  await page.waitForFunction(() => !document.querySelector('.term-matrix'), { timeout: 5000 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await run('matrix')
  assert.equal(await dialog.locator('.term-matrix').evaluate(el => getComputedStyle(el.firstElementChild).animationName), 'term-fall')
  await page.waitForFunction(() => !document.querySelector('.term-matrix'), { timeout: 5000 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await input.fill('')
  for (let index = 0; index < 20; index++) {
    await page.keyboard.press('Tab')
    assert.equal(await dialog.evaluate(el => el.contains(document.activeElement)), true)
  }
  await run('clear')
  assert.equal(await dialog.getByRole('log').innerText(), '')
  await dialog.getByRole('button', { name: 'English', exact: true }).click()
  await run('cat about.md')
  assert.match(await dialog.getByRole('log').innerText(), /sixth semester/)
  await dialog.getByRole('button', { name: 'Español', exact: true }).click()
  assert.match(await dialog.getByRole('log').innerText(), /sexto semestre/)
  await input.press('Escape')
  await dialog.waitFor({ state: 'detached' })
  assert.equal(await page.getByRole('button', { name: 'Abrir menú', exact: true }).evaluate(el => el === document.activeElement), true)
  await page.getByRole('button', { name: 'Abrir menú', exact: true }).click()
  await page.getByRole('button', { name: 'Workspace', exact: true }).click()
  assert.equal(await page.locator('dialog[open]').count(), 1)
  await page.keyboard.press('Escape')
  for (const [command, target] of [['open hero', 'main'], ['open about', 'about'], ['open skills', 'skills'], ['open projects', 'projects'], ['open contact', 'contact'], ['hire', 'contact']]) {
    await open(); await run(command)
    await page.waitForFunction(id => document.activeElement?.id === id, target)
    assert.equal(new URL(page.url()).hash, `#${target}`)
  }
  await open(); await run('projects')
  await dialog.getByRole('link', { name: 'PawPass', exact: true }).click()
  await page.waitForFunction(() => document.activeElement?.id === 'case-title')
  assert.equal(new URL(page.url()).hash, '#projects/pawpass')
  await open(); await run('exit')
  await dialog.waitFor({ state: 'detached' })
  await page.goto(`${base}/#contact`)
  await page.getByLabel('Nombre', { exact: false }).fill('Ana')
  await open(); await page.keyboard.press('Escape')
  assert.equal(await page.getByLabel('Nombre', { exact: false }).inputValue(), 'Ana')
  for (const width of [320, 375, 768, 1440]) {
    await page.setViewportSize({ width, height: 812 })
    await open()
    await run('help')
    await run('skills')
    assert.equal(await dialog.evaluate(el => el.scrollWidth > el.clientWidth), false)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    assert.equal(await dialog.locator('.term-scroll').evaluate(el => el.scrollHeight > el.clientHeight), true)
    assert.deepEqual(await dialog.locator('button:visible').evaluateAll(elements => elements.filter(el => { const r = el.getBoundingClientRect(); return r.width < 44 || r.height < 44 }).map(el => el.textContent)), [])
    await run('clear'); await run('whoami'); await run('projects')
    if (!process.env.SKIP_CAPTURES) await page.screenshot({ path: `${directory}/terminal-${width}.png` })
    await dialog.getByRole('button', { name: 'English', exact: true }).click()
    assert.match(await dialog.getByRole('log').innerText(), /I direct/)
    if (!process.env.SKIP_CAPTURES) await page.screenshot({ path: `${directory}/terminal-en-${width}.png` })
    await dialog.getByRole('button', { name: 'Español', exact: true }).click()
    await page.keyboard.press('Escape')
  }
  assert.deepEqual(errors, [])
  console.log('PASS Terminal: comandos, simulación segura, rutas/casos, historial y borrador, Tab/Shift+Tab, foco/Escape/exit, matrix temporal/reduced motion, clear, ES/EN vivo, overlays, formulario, scroll y 320–1440.')
} finally { await browser.close() }
