  await input.press('Escape')
  assert.equal(await launcher.evaluate(el=>document.activeElement===el),true)
  await page.keyboard.press(shortcut)
  await dialog.waitFor({state:'visible'})
  for (const [command,text] of [['pwd','/home/visitor/dnnnah/portfolio'],['ls -la','-rw-r--r--'],['git status','rama main'],['git stattus','rama main'],['git blame','00000000 (Donnovan 1)'],['easter','sudo make-coffee'],['cv','todavía no está disponible']]) {
   await run(command)
   assert.ok((await dialog.getByRole('log').innerText()).includes(text),command)
  }
  await dialog.getByRole('button',{name:'English',exact:true}).click()
  assert.match(await dialog.getByRole('log').innerText(), /On branch main/)
  assert.match(await dialog.getByRole('log').innerText(), /Simulated git blame/)
  await dialog.getByRole('button',{name:'Español',exact:true}).click()
  await run('clear')
  await input.fill('contact --msg "Hola, Donnovan"')
  const styles=await input.evaluate(el=>{const s=getComputedStyle(el);return {outline:s.outlineStyle,padding:parseFloat(s.paddingLeft),parentBorder:getComputedStyle(el.form).borderColor}})
  assert.equal(styles.outline,'none')
  assert.ok(styles.padding>=8)
  assert.equal(styles.parentBorder,'rgb(217, 205, 255)')
  if(platform==='MacIntel') await page.screenshot({path:`${directory}/entrada-desktop.png`})
