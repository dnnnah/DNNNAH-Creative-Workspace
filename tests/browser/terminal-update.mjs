    for(let i=0;i<geometry.children.length;i++)for(let j=i+1;j<geometry.children.length;j++){const a=geometry.children[i],b=geometry.children[j];assert.equal(a.left<b.right&&a.right>b.left&&a.top<b.bottom&&a.bottom>b.top,false,'Controles sin solapamiento')}
